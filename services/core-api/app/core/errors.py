"""RFC 7807 Problem Details error models and exception handlers.

Ensures all API errors (domain, validation, unhandled) emit standardized
JSON responses adhering to RFC 7807 (Problem Details for HTTP APIs).
"""

from typing import Any
from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

PROBLEM_JSON_MEDIA_TYPE = "application/problem+json"


class ProblemDetail(BaseModel):
    """RFC 7807 compliant problem details payload schema."""

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type.",
    )
    title: str = Field(description="Short, human-readable summary of the problem type.")
    status: int = Field(description="HTTP status code generated by origin server.")
    detail: str = Field(description="Human-readable explanation specific to this occurrence.")
    instance: str | None = Field(
        default=None,
        description="URI reference identifying the specific occurrence of the problem.",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="List of specific input validation errors (RFC 7807 extension).",
    )


# --- Custom Domain Exceptions ---


class AppException(Exception):
    """Base exception for application-level domain errors."""

    status_code: int = status.HTTP_500_INTERNAL_SERVER_ERROR
    error_type: str = "urn:error:internal-server-error"
    title: str = "Internal Server Error"

    def __init__(self, detail: str, error_type: str | None = None, title: str | None = None) -> None:
        super().__init__(detail)
        self.detail = detail
        if error_type:
            self.error_type = error_type
        if title:
            self.title = title


class NotFoundError(AppException):
    """Requested resource could not be found."""

    status_code = status.HTTP_404_NOT_FOUND
    error_type = "urn:error:not-found"
    title = "Resource Not Found"


class ConflictError(AppException):
    """Resource conflict (e.g. duplicate email, duplicate statement SHA-256)."""

    status_code = status.HTTP_409_CONFLICT
    error_type = "urn:error:conflict"
    title = "Resource Conflict"


class AuthenticationError(AppException):
    """Missing or invalid credentials."""

    status_code = status.HTTP_401_UNAUTHORIZED
    error_type = "urn:error:unauthorized"
    title = "Authentication Required"


class AuthorizationError(AppException):
    """User lacks permission to access the requested resource."""

    status_code = status.HTTP_403_FORBIDDEN
    error_type = "urn:error:forbidden"
    title = "Access Denied"


class BadRequestError(AppException):
    """Malformed request or invalid domain input."""

    status_code = status.HTTP_400_BAD_REQUEST
    error_type = "urn:error:bad-request"
    title = "Bad Request"


HTTP_422 = 422


class FileValidationError(AppException):
    """Uploaded file violates constraints (e.g. invalid signature, exceeds size)."""

    status_code = HTTP_422
    error_type = "urn:error:invalid-file"
    title = "Invalid File Payload"


# --- Exception Handlers ---


async def app_exception_handler(request: Request, exc: AppException) -> JSONResponse:
    """Handle custom application domain exceptions."""
    problem = ProblemDetail(
        type=exc.error_type,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        instance=str(request.url.path),
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
    )


async def validation_exception_handler(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    """Handle Pydantic request validation errors in RFC 7807 format."""
    invalid_params = []
    for err in exc.errors():
        field = " -> ".join(str(loc) for loc in err.get("loc", []))
        invalid_params.append({
            "name": field,
            "reason": err.get("msg", "Invalid value"),
            "type": err.get("type", "value_error"),
        })

    problem = ProblemDetail(
        type="urn:error:validation-error",
        title="Unprocessable Request Entity",
        status=HTTP_422,
        detail="The request payload failed validation checks. Inspect 'invalid_params' for details.",
        instance=str(request.url.path),
        invalid_params=invalid_params,
    )
    return JSONResponse(
        status_code=HTTP_422,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
    )


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Catch-all handler for unexpected internal exceptions."""
    problem = ProblemDetail(
        type="urn:error:internal-server-error",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected server error occurred. Please contact system support.",
        instance=str(request.url.path),
    )
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
    )
 

def setup_exception_handlers(app: FastAPI) -> None:
    """Register all RFC 7807 exception handlers on the FastAPI application."""
    app.add_exception_handler(AppException, app_exception_handler)
    app.add_exception_handler(RequestValidationError, validation_exception_handler)
    app.add_exception_handler(Exception, unhandled_exception_handler)
